-- V7을 모르는 이전 backend로 image rollback해도 기존 INSERT가 계속 동작하도록
-- 생략된 additive metadata를 DB 경계에서 legacy 값으로 보완한다.
CREATE OR REPLACE FUNCTION fill_legacy_alert_lifecycle_metadata()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.alarm_type IS NULL THEN
        NEW.alarm_type := CASE
            WHEN NEW.channel_id IS NOT NULL THEN 'THRESHOLD'
            WHEN NEW.message LIKE '구역 전체 수신 끊김%' THEN 'ZONE_SILENCE'
            ELSE 'DEVICE_SILENCE'
        END;
    END IF;
    IF NEW.scope_type IS NULL THEN
        NEW.scope_type := CASE
            WHEN NEW.channel_id IS NOT NULL THEN 'CHANNEL'
            WHEN NEW.message LIKE '구역 전체 수신 끊김%' THEN 'ZONE'
            ELSE 'DEVICE'
        END;
    END IF;
    IF NEW.notification_reason IS NULL THEN
        NEW.notification_reason := 'LEGACY';
    END IF;
    RETURN NEW;
END
$$;

CREATE TRIGGER trg_fill_legacy_alert_lifecycle_metadata
BEFORE INSERT ON alert
FOR EACH ROW
EXECUTE FUNCTION fill_legacy_alert_lifecycle_metadata();

